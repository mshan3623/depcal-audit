"""내용연수 5·6년 **밖**의 손계산 절대 골든값 — 별표4 격자의 빈칸을 채운다 (감사 G12).

배경(docs/IMPROVEMENT_PLAN_2026-09-05.md 트랙 B1): 상각률표 자체는
`test_rate_table_statutory.py`가 법령 PDF ↔ 픽스처 ↔ vcore ↔ core로 2~60년 전 엔트리를
닫았다. 닫히지 않은 것은 **「표 엔트리 × 컨벤션」 격자**다 — 손계산 골든은 정액 5년·정률
5년·무형 6년뿐이고, 더존 실측 105건은 전부 5년이다. G1·G2(float 1원 하향)가 5년 밖에서만
발화한 것이 이 빈칸을 그대로 그린 것이고, 3.6.0의 정수 산술 전환은 59개 엔트리 전부의
연 상각액을 바꿔놓고도 여전히 5년 하나로만 밖에서 검증되고 있었다.

고르는 기준은 임의가 아니라 **컨벤션이 내용연수에 의존하는 지점**이다:
  · 별표4 정액율 × n ≠ 1 인 연수 → 정액에도 종료해 잔재가 생긴다(G28이 나온 축).
    7년 0.142×7 = 0.994, 14년 0.071×14 = 0.994.
  · G1·G2 발화 연수 → 정수 산술 전환이 5년 밖에서 옳은지 처음 확인하는 칸. 정률 9년(0.284)은
    실무 금액대 표본에서 71.3% 발화했던 연수다.

컨벤션(기존 손계산 골든과 동일):
  · 정액 연 상각 = round(취득원가 × 정액율) = (cost × s + 500) // 1000
  · 정률 연 상각 = int(기초장부가 × 정률율) = book × d // 1000
  · 종료해 = 직전 장부가 − 비망가(1,000)

한계: 이것은 '컨벤션 손계산' 앵커지 외부 실측이 아니다. 같은 규칙 해석의 재확인일 뿐이므로
표 엔트리별 **실측**은 여전히 5년 하나다(G12-B, 대장 표본 확대 — 미해소).
"""
import pytest

from vcore import declining_balance, straight_line
from vcore.rate_table import STATUTORY_PERMILLE

COST = 100_000_000
MEMORANDUM = 1_000


def _yearly(rows):
    return [(r.fiscal_year, r.months, r.depreciation, r.accumulated, r.book_value) for r in rows]


# ── 정액 7년 (별표4 0.142) ───────────────────────────────────────────────
# 연 상각 = round(1억 × 0.142) = 14,200,000. 0.142 × 7 = 0.994 이므로 6년 뒤 장부가
# 14,800,000이 남고, 종료해가 그 잔액에서 비망가만 남긴다(평년보다 599,000 크다).
GOLDEN_SL_7 = [
    (2026, 12, 14_200_000, 14_200_000, 85_800_000),
    (2027, 12, 14_200_000, 28_400_000, 71_600_000),
    (2028, 12, 14_200_000, 42_600_000, 57_400_000),
    (2029, 12, 14_200_000, 56_800_000, 43_200_000),
    (2030, 12, 14_200_000, 71_000_000, 29_000_000),
    (2031, 12, 14_200_000, 85_200_000, 14_800_000),
    (2032, 12, 14_799_000, 99_999_000,      1_000),   # 종료해 = 14,800,000 − 1,000
]

# ── 정액 14년 (별표4 0.071) ──────────────────────────────────────────────
# 연 상각 = round(1억 × 0.071) = 7,100,000. 0.071 × 14 = 0.994 — 7년과 같은 축, 다른 엔트리.
GOLDEN_SL_14 = [
    (2026, 12, 7_100_000,  7_100_000, 92_900_000),
    (2027, 12, 7_100_000, 14_200_000, 85_800_000),
    (2028, 12, 7_100_000, 21_300_000, 78_700_000),
    (2029, 12, 7_100_000, 28_400_000, 71_600_000),
    (2030, 12, 7_100_000, 35_500_000, 64_500_000),
    (2031, 12, 7_100_000, 42_600_000, 57_400_000),
    (2032, 12, 7_100_000, 49_700_000, 50_300_000),
    (2033, 12, 7_100_000, 56_800_000, 43_200_000),
    (2034, 12, 7_100_000, 63_900_000, 36_100_000),
    (2035, 12, 7_100_000, 71_000_000, 29_000_000),
    (2036, 12, 7_100_000, 78_100_000, 21_900_000),
    (2037, 12, 7_100_000, 85_200_000, 14_800_000),
    (2038, 12, 7_100_000, 92_300_000,  7_700_000),
    (2039, 12, 7_699_000, 99_999_000,      1_000),   # 종료해 = 7,700,000 − 1,000
]

# ── 정률 9년 (별표4 0.284) ───────────────────────────────────────────────
# 매년 int(기초장부가 × 0.284). 1년차 28,400,000은 float(0.284)로 곱하면 28,399,999로
# 내려가던 값이다(G1) — 정수 산술 전환이 5년 밖에서 옳은지 여기서 처음 고정된다.
GOLDEN_DB_9 = [
    (2026, 12, 28_400_000, 28_400_000, 71_600_000),
    (2027, 12, 20_334_400, 48_734_400, 51_265_600),
    (2028, 12, 14_559_430, 63_293_830, 36_706_170),
    (2029, 12, 10_424_552, 73_718_382, 26_281_618),
    (2030, 12,  7_463_979, 81_182_361, 18_817_639),
    (2031, 12,  5_344_209, 86_526_570, 13_473_430),
    (2032, 12,  3_826_454, 90_353_024,  9_646_976),
    (2033, 12,  2_739_741, 93_092_765,  6_907_235),
    (2034, 12,  6_906_235, 99_999_000,      1_000),   # 종료해 = 6,907,235 − 1,000
]


def test_straight_line_7_years_matches_handcalc():
    assert _yearly(straight_line.schedule(COST, 7, 2026, 1)) == GOLDEN_SL_7


def test_straight_line_14_years_matches_handcalc():
    assert _yearly(straight_line.schedule(COST, 14, 2026, 1)) == GOLDEN_SL_14


def test_declining_9_years_matches_handcalc():
    assert _yearly(declining_balance.schedule(COST, 9, 2026, 1)) == GOLDEN_DB_9


@pytest.mark.parametrize("life,permille,annual", [(7, 142, 14_200_000),
                                                  (14, 71, 7_100_000),
                                                  (9, 111, 11_100_000),
                                                  (41, 25, 2_500_000)])
def test_straight_line_annual_is_exact_integer(life, permille, annual):
    """평년 연 상각액이 별표4 1000분율의 정확한 정수다 — float 곱셈이 1원 내리던 자리(G2)."""
    assert STATUTORY_PERMILLE[life][0] == permille
    assert (COST * permille + 500) // 1000 == annual
    assert straight_line.schedule(COST, life, 2026, 1)[0].depreciation == annual


@pytest.mark.parametrize("life", [7, 9, 14, 41])
def test_terminal_book_value_is_memorandum(life):
    """어느 연수든 마지막 행의 장부가는 비망가 1,000이다 — 종료해 잔재가 남지 않는다."""
    rows = straight_line.schedule(COST, life, 2026, 1)
    assert rows[-1].book_value == MEMORANDUM
    assert declining_balance.schedule(COST, life, 2026, 1)[-1].book_value == MEMORANDUM


def test_straight_line_41_years_completes_before_useful_life_ends():
    """정액율 × n > 1 인 연수(41년: 0.025 × 41 = 1.025)는 내용연수 종료 **전에** 상각이 끝난다.

    40년차에 장부가가 비망가에 닿는다. 이 축은 5·6년 골든에 없던 칸이다.

    ※ 미결(2026-09-05 B1에서 발견): vcore는 그 뒤에 상각액 0인 41년차 행을 하나 더 붙인다.
      상각이 끝난 자산을 대장에 0으로 계속 표시하는 실무와 맞을 수도, 분리자산 경로가
      같은 상황에서 `[]`를 돌려주는 것과 어긋날 수도 있다. 실측 앵커가 0건이라 어느 쪽이
      옳은지 코드가 정하지 못한다 — 여기서는 **현 동작을 골든으로 굳히지 않고** 상각이
      40년차에 끝난다는 사실만 고정한다(감사 G12-B 표본 확보 시 판정).
    """
    rows = straight_line.schedule(COST, 41, 2026, 1)
    charged = [r for r in rows if r.depreciation > 0]
    assert len(charged) == 40
    assert charged[-1].depreciation == 2_499_000        # 2,500,000 − 비망가
    assert charged[-1].book_value == MEMORANDUM
    assert all(r.depreciation == 0 and r.book_value == MEMORANDUM for r in rows[len(charged):])
